# Positive Indexing
print("---------Positive Indexing---------")
s = 'hello world'
print(s[1])


# Negative Indexing
print("---------Negative Indexing---------")
s = 'hello world'
print(s[-3])
print(s[-1])


# Slicing
print("---------------Slicing--------------")
s = 'hello world'
print(s[0:8])
print(s[4:8:2])


# Reverse slicing
print("-------Reverse Slicing---------")
s = 'hello world'
print(s[-1:-12:-1])
print(s[-1:-12:-2])


